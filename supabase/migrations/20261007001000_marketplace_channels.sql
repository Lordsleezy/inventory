create or replace function public.portal_set_unit_listed_on(p_sku text,p_channels text[])
returns text[] language plpgsql security definer set search_path=public as $$
declare v_store uuid:=public.portal_store_id(); v_channels text[];
begin
  if v_store is null then raise exception 'portal_access_denied' using errcode='42501'; end if;
  select coalesce(array_agg(distinct lower(btrim(x)) order by lower(btrim(x))),'{}'::text[]) into v_channels
  from unnest(coalesce(p_channels,'{}'::text[])) x
  where lower(btrim(x)) in ('vendoo','mercari','poshmark','facebook','depop','other');
  update public.units set listed_on=v_channels,updated_at=now() where store_id=v_store and sku=p_sku;
  if not found then raise exception 'unit_not_found' using errcode='P0002'; end if;
  update public.listings set status='delisted',delisted_at=now()
    where store_id=v_store and sku=p_sku and channel in ('vendoo','mercari','poshmark','facebook','depop','other')
      and not(channel=any(v_channels)) and status='listed';
  insert into public.listings(store_id,sku,channel,status,listed_at,delisted_at)
    select v_store,p_sku,x,'listed',now(),null from unnest(v_channels) x
    on conflict(store_id,sku,channel) do update set status='listed',listed_at=coalesce(public.listings.listed_at,now()),delisted_at=null;
  return v_channels;
end $$;
revoke all on function public.portal_set_unit_listed_on(text,text[]) from public,anon;
grant execute on function public.portal_set_unit_listed_on(text,text[]) to authenticated;

create or replace function public.marketplace_ingest_sale(p_store uuid,p_sku text,p_channel text,p_price_cents int,p_order_number text,p_message_id text,p_marketplace text,p_item_title text,p_ship_by date,p_fulfillment text,p_buyer jsonb,p_confidence numeric)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_sale public.sales; v_existing bigint; v_unit public.units;
begin
  perform public.assert_service();
  if lower(p_channel) not in ('mercari','poshmark','facebook','depop','other') then raise exception 'invalid_marketplace'; end if;
  select sale_id into v_existing from public.marketplace_email_sales where store_id=p_store and message_id=p_message_id;
  if v_existing is not null then return v_existing; end if;
  select * into v_unit from public.units where store_id=p_store and sku=p_sku for update;
  if not found or v_unit.state<>'available' then raise exception 'unit_not_available'; end if;
  update public.listings set status='delisted',delisted_at=now() where store_id=p_store and sku=p_sku and channel=p_channel;
  v_sale:=public.finalize_sale(p_sku=>p_sku,p_channel=>p_channel,p_price_cents=>p_price_cents,p_payment_method=>'marketplace',
    p_payment_id=>'marketplace:'||p_marketplace||':'||coalesce(p_order_number,p_message_id),p_note=>'Marketplace order '||coalesce(p_order_number,p_message_id));
  insert into public.marketplace_email_sales(store_id,message_id,marketplace,state,sku,item_title,order_number,sale_price_cents,ship_by,fulfillment,buyer,confidence,sale_id)
  values(p_store,p_message_id,p_marketplace,'matched',p_sku,p_item_title,p_order_number,p_price_cents,p_ship_by,p_fulfillment,coalesce(p_buyer,'{}'::jsonb),p_confidence,v_sale.id)
  on conflict(store_id,message_id) do update set state='matched',sale_id=excluded.sale_id,sku=excluded.sku,reason=null;
  insert into public.web_orders(store_id,sku,sale_id,status,fulfillment,buyer_name,buyer_email,buyer_phone,
    ship_line1,ship_line2,ship_city,ship_region,ship_postal,ship_country,item_cents,shipping_cents,tax_cents,total_cents,
    payment_id,created_at,updated_at,order_no,paid_at,payment_env,channel,ship_by)
  values(p_store,p_sku,v_sale.id,'paid',case when p_fulfillment='pickup' then 'pickup' else 'ship' end,
    p_buyer->>'name',p_buyer->>'email',p_buyer->>'phone',p_buyer->>'line1',p_buyer->>'line2',p_buyer->>'city',
    p_buyer->>'region',p_buyer->>'postal',coalesce(p_buyer->>'country','US'),p_price_cents,0,0,p_price_cents,
    'marketplace:'||p_marketplace||':'||coalesce(p_order_number,p_message_id),now(),now(),
    upper(p_marketplace)||'-'||left(regexp_replace(coalesce(p_order_number,p_message_id),'[^A-Za-z0-9-]','','g'),32),now(),'production',lower(p_channel),p_ship_by)
  on conflict do nothing;
  return v_sale.id;
end $$;
revoke all on function public.marketplace_ingest_sale(uuid,text,text,int,text,text,text,text,date,text,jsonb,numeric) from public,anon,authenticated;
grant execute on function public.marketplace_ingest_sale(uuid,text,text,int,text,text,text,text,date,text,jsonb,numeric) to service_role;

create or replace function public.portal_complete_marketplace_delist(p_id bigint)
returns void language plpgsql security definer set search_path=public as $$
declare v_store uuid:=public.portal_store_id();
begin
  if v_store is null then raise exception 'portal_access_denied' using errcode='42501'; end if;
  update public.delist_tasks set completed_at=now(),completed_by=auth.uid()
  where id=p_id and store_id=v_store and channel<>'ebay' and completed_at is null;
end $$;
revoke all on function public.portal_complete_marketplace_delist(bigint) from public,anon;
grant execute on function public.portal_complete_marketplace_delist(bigint) to authenticated;

update public.store_settings
set value=coalesce((select jsonb_agg(to_jsonb(lower(btrim(x)))) from jsonb_array_elements_text(value) x where lower(btrim(x))<>'ebay'),'[]'::jsonb)
where key='online_channels' and jsonb_typeof(value)='array';
update public.store_settings set value='true'::jsonb where key='ebay_disabled';
insert into public.store_settings(store_id,key,value) select id,'google_merchant_enabled','false'::jsonb from public.stores on conflict(store_id,key) do nothing;
update public.listings set status='delisted',delisted_at=coalesce(delisted_at,now())
where channel='ebay' and status in ('listed','pending_delist');
update public.delist_tasks set completed_at=coalesce(completed_at,now())
where channel='ebay' and completed_at is null;

select (select count(*) from public.google_sync_queue) as google_queue,
       (select count(*) from public.marketplace_email_sales where state='needs_review') as marketplace_reviews,
       (select count(*) from public.listings where channel='ebay' and status in ('listed','pending_delist')) as ebay_active_rows;

commit;
