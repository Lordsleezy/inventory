create or replace function public.queue_google_unit(p_store uuid,p_sku text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_store is null or nullif(btrim(p_sku),'') is null then return; end if;
  insert into public.google_sync_queue(store_id,sku) values(p_store,btrim(p_sku))
  on conflict(store_id,sku) do update set action='upsert',attempts=0,last_error=null,queued_at=now();
end $$;

create or replace function public.queue_google_unit_trigger()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  perform public.queue_google_unit(coalesce(new.store_id,old.store_id),coalesce(new.sku,old.sku));
  if tg_op='UPDATE' and (old.store_id,old.sku) is distinct from (new.store_id,new.sku) then
    perform public.queue_google_unit(old.store_id,old.sku);
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end $$;

